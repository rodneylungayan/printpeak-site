// Checks the image slots in public/images. Warns on missing, oversized or wrong-ratio files.
// Run: npm run check:assets  (warnings only; it never fails the build)
import { existsSync, readFileSync, statSync } from "node:fs";

const slots = [
  { path: "public/images/logo/logo.svg", optional: true, note: "real logo (a text wordmark is used until then)" },
  { path: "public/images/hero/hero.webp", optional: true, ratio: 1.2, maxKb: 350, note: "hero photo, 1200×1000" },
  { path: "public/images/og-default/og-default.png", optional: true, ratio: 1200 / 630, maxKb: 900, note: "share image (generated by app/opengraph-image.tsx until then)" },
];

function pngSize(buf) {
  if (buf.toString("ascii", 1, 4) !== "PNG") return null;
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
}

function webpSize(buf) {
  if (buf.toString("ascii", 8, 12) !== "WEBP") return null;
  const chunk = buf.toString("ascii", 12, 16);
  if (chunk === "VP8X") return { w: 1 + buf.readUIntLE(24, 3), h: 1 + buf.readUIntLE(27, 3) };
  if (chunk === "VP8 ") return { w: buf.readUInt16LE(26) & 0x3fff, h: buf.readUInt16LE(28) & 0x3fff };
  return null;
}

let warnings = 0;
for (const slot of slots) {
  if (!existsSync(slot.path)) {
    console.log(`${slot.optional ? "info" : "WARN"}  missing ${slot.path} — ${slot.note}`);
    if (!slot.optional) warnings++;
    continue;
  }
  const kb = statSync(slot.path).size / 1024;
  if (slot.maxKb && kb > slot.maxKb) {
    console.log(`WARN  ${slot.path} is ${kb.toFixed(0)} KB (max ${slot.maxKb} KB)`);
    warnings++;
  }
  if (slot.ratio) {
    const buf = readFileSync(slot.path);
    const size = pngSize(buf) ?? webpSize(buf);
    if (size && Math.abs(size.w / size.h - slot.ratio) > 0.03) {
      console.log(`WARN  ${slot.path} is ${size.w}×${size.h}; expected ratio ${slot.ratio.toFixed(2)}`);
      warnings++;
    }
  }
  console.log(`ok    ${slot.path}`);
}
console.log(`\n${warnings} warning(s).`);
